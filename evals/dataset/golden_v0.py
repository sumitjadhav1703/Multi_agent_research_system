def dumps() -> str:
    return "".join(json.dumps(item, ensure_ascii=False, sort_keys=True) + "\n" for item in CASES)


def main() -> None:
    path = Path(__file__).with_name("golden_v0.jsonl")
    path.write_text(dumps(), encoding="utf-8")
    print(f"wrote {path} cases={len(CASES)}")


if __name__ == "__main__":
    main()
